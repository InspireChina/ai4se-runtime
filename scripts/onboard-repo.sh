  "$AI4SE/repository" \
  "$AI4SE/knowledge" \
  "$AI4SE/learning" \
  "$AI4SE/rules" \
  "$AI4SE/skills" \
  "$AI4SE/index" \
  "$STORY"

# Minimal index stubs (empty knowledge allowed; structure required)
