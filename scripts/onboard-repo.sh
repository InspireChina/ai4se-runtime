if [[ ! -f "$AI4SE/repository/entries.yaml" ]]; then
  {
    echo "# Auto-detected build entry pointers."
    echo "# Repository-wide tests remain unknown until a Story establishes a target-relevant probe."
    build_lines=()
    detect_dir() {
      local dir="$1"
      local prefix="$2"
      if [[ -f "$dir/pom.xml" ]]; then
        build_lines+=("  - ${prefix}mvn -q -DskipTests package")
      fi
      if [[ -f "$dir/package.json" ]]; then
        if grep -Eq '"build"[[:space:]]*:' "$dir/package.json" 2>/dev/null; then
          build_lines+=("  - ${prefix}npm run build")
        fi
      fi
      if [[ -f "$dir/build.gradle" || -f "$dir/build.gradle.kts" ]]; then
        build_lines+=("  - ${prefix}./gradlew assemble")
      fi
    }
    detect_dir "$ROOT" ""
    for sub in "$ROOT"/*/; do
      [[ -d "$sub" ]] || continue
      sub="${sub%/}"
      base="$(basename "$sub")"
      case "$base" in
        target|node_modules|.git|.idea|build|dist|out) continue ;;
      esac
      detect_dir "$sub" "cd ${base} && "
    done
    if [[ ${#build_lines[@]} -eq 0 ]]; then
      echo "build: unknown"
      echo "test: unknown"
    else
      echo "build:"
      printf '%s\n' "${build_lines[@]}"
      echo "test: unknown"
    fi
  } > "$AI4SE/repository/entries.yaml"
fi

# A customer can only judge an onboarding result if the structural facts are
# visible and cite their source.  These documents deliberately keep unknowns
# visible: neither this shell probe nor a later model call is allowed to turn a
# guessed architecture/business rule into an established repository fact.
write_repository_facts() {
  local out="$AI4SE/repository/facts.md"
  local git_head=""
  local git_branch=""
  local java_count=0
  local test_count=0
  local controller_count=0
  local source_refs=()

  # A linked Git worktree has a .git *file* that points at the common Git dir.
  # Ask Git instead of checking for a directory so facts are equally traceable
  # in the customer main checkout and the isolated Story worktree.
  if git -C "$ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    git_head="$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || true)"
    git_branch="$(git -C "$ROOT" branch --show-current 2>/dev/null || true)"
    source_refs+=("- git metadata: \`.git/\`")
  fi
  if [[ -f "$ROOT/pom.xml" ]]; then source_refs+=("- Maven descriptor: \`pom.xml\`"); fi
  if [[ -f "$ROOT/package.json" ]]; then source_refs+=("- Node descriptor: \`package.json\`"); fi
  if [[ -f "$ROOT/build.gradle" || -f "$ROOT/build.gradle.kts" ]]; then source_refs+=("- Gradle descriptor: \`build.gradle*\`"); fi
  java_count="$(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/target' -prune -o -name '*.java' -type f -print 2>/dev/null | wc -l | tr -d ' ')"
  test_count="$(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/target' -prune -o \( -name '*Test.java' -o -name '*Tests.java' \) -type f -print 2>/dev/null | wc -l | tr -d ' ')"
  controller_count="$(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/target' -prune -o \( -name '*Controller.java' -o -name '*Resource.java' \) -type f -print 2>/dev/null | wc -l | tr -d ' ')"

  {
    echo "# Repository Facts"
    echo
    echo "> Generated by \`onboard-repo.sh\` from filesystem and Git metadata; this is an evidence index, not an architecture recommendation."
    echo
    echo "## Snapshot"
    echo "- workspace: \`$ROOT\`"
    if [[ -n "$git_head" ]]; then echo "- git_head: \`$git_head\`"; fi
    if [[ -n "$git_branch" ]]; then echo "- git_branch: \`$git_branch\`"; fi
    echo "- observed_at_utc: \`$(date -u +%Y-%m-%dT%H:%M:%SZ)\`"
    echo
    echo "## Observable inventory"
    echo "- Java source files: $java_count"
    echo "- Java test-named files: $test_count"
    echo "- Controller/Resource-named files: $controller_count"
    echo "- build entry declarations: \`.ai4se/repository/entries.yaml\` (not executed by onboard)"
    echo "- verification capability inventory: \`.ai4se/repository/verification-capabilities.yaml\` (not executed by onboard)"
    echo
    echo "## Sources"
    if [[ ${#source_refs[@]} -eq 0 ]]; then echo "- No recognised build descriptor found"; else printf '%s\n' "${source_refs[@]}"; fi
    echo
    echo "## Unknowns requiring confirmation"
    echo "- Which declared build/test entry is valid in this environment."
    echo "- Runtime dependencies, credentials and external services."
    echo "- Business ownership, domain meanings and release policy."
  } > "$out"
}

write_module_map() {
  local out="$AI4SE/repository/module-map.md"
  {
    echo "# Module Map (Observed)"
    echo
    echo "> This map lists structural locations only. A path is not evidence of responsibility or business semantics."
    echo
    echo "## Root build descriptors"
    for file in pom.xml package.json build.gradle build.gradle.kts settings.gradle settings.gradle.kts; do
      if [[ -f "$ROOT/$file" ]]; then echo "- \`$file\`"; fi
    done
    echo
    echo "## Maven modules declared by root pom"
    local modules
    modules="$(grep -E '^\s*<module>[^<]+</module>' "$ROOT/pom.xml" 2>/dev/null | sed -E 's/.*<module>([^<]+)<\/module>.*/\1/' || true)"
    if [[ -n "$modules" ]]; then
      while IFS= read -r m; do [[ -n "$m" ]] && echo "- \`$m\` (source: \`pom.xml\`)"; done <<< "$modules"
    else
      echo "- none observed or root pom.xml absent"
    fi
    echo
    echo "## Source roots (depth <= 4)"
    local found=0
    while IFS= read -r root_path; do
      [[ -z "$root_path" ]] && continue
      echo "- \`${root_path#$ROOT/}\`"
      found=1
    done < <(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/target' -prune -o -type d \( -path '*/src/main' -o -path '*/src/test' -o -path '*/src/main/java' -o -path '*/src/test/java' -o -path '*/src/main/resources' -o -path '*/src/test/resources' \) -print 2>/dev/null | sort)
    if [[ "$found" -eq 0 ]]; then echo "- none observed"; fi
    echo
    echo "## Unknowns"
    echo "- Dependency direction and module ownership are not inferred by the filesystem probe."
    echo "- API/data boundaries must be established by Story analysis with source references."
  } > "$out"
}

write_verification_capabilities() {
  local out="$AI4SE/repository/verification-capabilities.yaml"
  local java_tests node_projects maven_skip
  java_tests="$(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/target' -prune -o \( -name '*Test.java' -o -name '*Tests.java' \) -type f -print 2>/dev/null | wc -l | tr -d ' ')"
  node_projects="$(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/node_modules' -prune -o -name package.json -type f -print 2>/dev/null | wc -l | tr -d ' ')"
  # grep returns 1 when no descriptor contains this property.  Under pipefail that is an
  # expected observation, not an onboarding failure.
  maven_skip="$( (grep -R -E -l '<maven\.test\.skip>[[:space:]]*true' "$ROOT" --include='pom.xml' 2>/dev/null || true) | wc -l | tr -d ' ')"
  {
    echo "# Verification Capability Map"
    echo "# Generated from repository descriptors and file names. No test command is run here."
    echo "baseline_status: inventory_only"
    echo "java_test_named_files: $java_tests"
    echo "node_package_json_files: $node_projects"
    echo "maven_descriptors_with_test_skip_true: $maven_skip"
    echo "repository_wide_test_entry: not_configured"
    echo "story_delivery_rule: frozen_acceptance_probes_required"
    echo "notes:"
    echo "  - Existing test classes and package scripts are assets to inspect, not evidence that they run locally."
    echo "  - External services are considered only if a target Story touches them."
    echo "  - API, DB, UI and messaging Stories must freeze at least one probe across the changed boundary."
    echo "observed_node_scripts:"
    while IFS= read -r package; do
      [[ -z "$package" ]] && continue
      local rel
      rel="${package#$ROOT/}"
      echo "  - path: $rel"
      if grep -Eq '"test"[[:space:]]*:' "$package" 2>/dev/null; then
        echo "    test_script: declared"
      else
        echo "    test_script: not_configured"
      fi
    done < <(find "$ROOT" -path "$ROOT/.git" -prune -o -path '*/node_modules' -prune -o -name package.json -type f -print 2>/dev/null | sort)
  } > "$out"
}

write_onboard_report() {
  local out="$AI4SE/repository/onboard-report.md"
  {
    echo "# Onboard Report"
    echo
    echo "- status: FACTS_CAPTURED_NOT_EXECUTION_VERIFIED"
    echo "- facts: \`.ai4se/repository/facts.md\`"
    echo "- module_map: \`.ai4se/repository/module-map.md\`"
    echo "- baseline: \`.ai4se/repository/baseline.md\`"
    echo "- entries: \`.ai4se/repository/entries.yaml\`"
    echo "- verification_capabilities: \`.ai4se/repository/verification-capabilities.yaml\`"
    echo
    echo "## Next automatic action"
    echo
    echo "1. Run bounded semantic Discovery using the observable facts."
    echo "2. Promote source-cited Discovery output as working knowledge; business Unknowns remain unresolved."
    echo "3. Start a Story; its frozen acceptance probes establish the delivery verification boundary."
    echo
    echo "No command was executed by onboarding, and no business knowledge was asserted."
  } > "$out"
}

# Refresh fact documents: they are a snapshot, unlike operator-owned entries.
write_repository_facts
write_module_map
write_verification_capabilities
write_onboard_report

