#!/usr/bin/env bash
# 01 Repository Intelligence · 客户仓事实摸底（只记录可观察事实，不替人做业务判断）
# Usage: ./scripts/onboard-repo.sh /path/to/customer-repo
set -euo pipefail

ROOT="${1:-}"
if [[ -z "$ROOT" || ! -d "$ROOT" ]]; then
  echo "Usage: $0 /path/to/customer-repo" >&2
  exit 1
fi

ROOT="$(cd "$ROOT" && pwd)"
