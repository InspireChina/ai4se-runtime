fi

write_maven_baseline() {
  local pom="$ROOT/pom.xml"
  local out="$AI4SE/repository/baseline.md"
  local modules
  modules="$(grep -E '^\s*<module>[^<]+</module>' "$pom" 2>/dev/null | sed -E 's/.*<module>([^<]+)<\/module>.*/\1/' || true)"
  local java_ver
  java_ver="$(grep -E '<java.version>' "$pom" 2>/dev/null | head -1 | sed -E 's/.*<java.version>([^<]+)<\/java.version>.*/\1/' || true)"
  local artifact=""
  # Prefer project artifactId after </parent> (skip spring-boot parent id). Else first artifactId.
  if grep -q '</parent>' "$pom" 2>/dev/null; then
    artifact="$(sed -n '/<\/parent>/,$p' "$pom" | grep -E '<artifactId>' | head -1 \
      | sed -E 's/.*<artifactId>([^<]+)<\/artifactId>.*/\1/' || true)"
  fi
  if [[ -z "$artifact" ]]; then
    # No parent block (or empty): take first artifactId under project (usually correct).
    artifact="$(grep -E '<artifactId>' "$pom" 2>/dev/null | head -1 \
      | sed -E 's/.*<artifactId>([^<]+)<\/artifactId>.*/\1/' || true)"
  fi
  # Guard: never record known parent BOM ids as project id
  if [[ "$artifact" == "spring-boot-starter-parent" || "$artifact" == "spring-boot-dependencies" ]]; then
    artifact="$(grep -E '<artifactId>' "$pom" 2>/dev/null | grep -v starter-parent | grep -v spring-boot-dependencies | head -1 \
      | sed -E 's/.*<artifactId>([^<]+)<\/artifactId>.*/\1/' || true)"
  fi

  {
    echo "# Repository Baseline (Facts / Map — no AI analysis)"
    echo
    echo "> Generated by onboard-repo.sh from observable files. Edit to correct; do not add change suggestions."
    echo
    echo "## Identity"
    echo "- root: \`$ROOT\`"
    if [[ -n "$artifact" ]]; then
      echo "- root artifactId: \`$artifact\`"
    fi
    if [[ -n "$java_ver" ]]; then
      echo "- java.version (from pom): \`$java_ver\`"
    fi
    echo "- build system: Maven (pom.xml present)"
    echo
    echo "## Modules"
    if [[ -n "$modules" ]]; then
      while IFS= read -r m; do
        [[ -z "$m" ]] && continue
        echo "- \`$m\`"
      done <<< "$modules"
    else
      echo "- (no \`<module>\` entries parsed from root pom.xml)"
    fi
    echo
    echo "## Build entry"
    echo "- see \`.ai4se/repository/entries.yaml\`"
    echo "- default probe: \`mvn -q -DskipTests package\`"
    echo
    echo "## Test entry"
    echo "- repository-wide test command: not inferred; see \`.ai4se/repository/verification-capabilities.yaml\`"
    echo "- delivery verification is defined per Story by frozen acceptance probes and any explicitly configured quality gates"
    echo
    echo "## Risk surface"
    echo "- Existing historical tests may require services (DB/Redis) and are inventory assets, not an automatic onboarding gate"
    echo
    echo "## Architecture notes"
    echo "- Facts derived from root pom.xml module list and properties only"
    echo
    echo "## Digitization status"
    echo "| Slot | Status |"
    echo "|------|--------|"
    echo "| entries.yaml | probed or unknown |"
    echo "| baseline.md | maven probe (this file) |"
    echo "| knowledge/learning/rules/skills | structure only until Lifecycle |"
  } > "$out"
}

if [[ ! -f "$AI4SE/repository/baseline.md" ]]; then
  if [[ -f "$ROOT/pom.xml" ]]; then
    write_maven_baseline
  elif [[ -f "$ROOT/package.json" ]]; then
    cat > "$AI4SE/repository/baseline.md" <<EOF
